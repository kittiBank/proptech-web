import type { NewProject, ProjectStatus, ProjectType, TransitLineId, TransitStation } from "@/types/property";
import { photos } from "./images";

/**
 * Developer projects behind `GET /projects`. Compact rows keep the table
 * readable; `row()` expands them into the API shape.
 */

type Row = [
  slug: string,
  name: string,
  developer: string,
  type: ProjectType,
  district: string,
  startingPrice: number,
  status: ProjectStatus,
  progress: number | undefined,
  completionYear: number,
  units: number,
  unitsLeft: number,
  station: [TransitLineId, string, string, number] | undefined,
  size: [number, number],
  launchedAt: string,
  photo: keyof typeof photos,
  summary: string,
];

/** Promoted in the featured slot at the top of `/projects`. */
const FEATURED_SLUG = "aster-sathorn";

function row(r: Row, i: number): NewProject {
  const [
    slug,
    name,
    developer,
    type,
    district,
    startingPrice,
    status,
    progress,
    completionYear,
    units,
    unitsLeft,
    station,
    size,
    launchedAt,
    photo,
    summary,
  ] = r;
  const stop: TransitStation | undefined = station && { line: station[0], code: station[1], name: station[2] };
  return {
    id: `np-${String(i + 1).padStart(2, "0")}`,
    slug,
    name,
    developer,
    type,
    district,
    startingPrice,
    status,
    progress,
    completionYear,
    units,
    unitsLeft,
    station: stop,
    stationDistance: station?.[3],
    sizeRange: { min: size[0], max: size[1], unit: type === "condo" ? "sqm" : "sqwah" },
    launchedAt,
    image: { src: photos[photo], alt: `ภาพโครงการ${name}` },
    summary,
    isFeatured: slug === FEATURED_SLUG || undefined,
  };
}

